#!/usr/bin/env python3
"""l3poses.py OUT.tcl [POOL_PREFIX]: the scripted enemies of tools/bstest/l3field.tcl (level 3's frame cache
on the screen, docs/LEVEL3.md 4 checks 3-5, its step C) from level 3's play-field frames (POOL_l3.json
"field", default build/msx/sprites): phases of LF_LEN ticks, each a list of parts that cycle through their
frames, with a hit flash (every part's white copy: the frame id's bit 7, msx/bob.asm fb_add) every 16th
tick: Cain (his legs, his 64 x 32 and 48 x 16 parts), type 21 (legs, torso), the truck (its body and 48 x
24 part), type 51, type 35 with the rocket and a debris part, and Cain's legs beside type 21's (both in
the cache's place 0: a place shared by frames on screen together, loaded again for each). Writes
::lf_phases: per phase {name {{frames period dx dy} ...}}."""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
LF_LEN = 150


def main() -> int:
    out = Path(sys.argv[1])
    pre = Path(sys.argv[2]) if len(sys.argv) > 2 else ROOT / "build/msx/sprites"
    field = json.loads(pre.with_name(pre.name + "_l3.json").read_text())["field"]
    by = lambda **k: [f["fid"] for f in field if all(f[a] == v for a, v in k.items()) and f["look"] == f["fid"]]  # noqa: E731
    cain_legs = [f["fid"] for f in field if (f["w"], f["h"]) in ((48, 44), (64, 34))]
    cain64 = by(w=64, h=32)
    cain48 = [f["fid"] for f in field if (f["w"], f["h"]) == (48, 16) and f["proc"] == "obj22_update"]
    w21_legs, w21_torso = by(w=64, h=40), [f["fid"] for f in field if (f["w"], f["h"]) == (48, 28) and f["proc"] == "obj21_update"]
    truck, part = by(w=80, h=48), [f["fid"] for f in field if (f["w"], f["h"]) == (48, 24)]
    w51 = by(w=48, h=49)
    w35 = [f["fid"] for f in field if f["proc"] == "obj35_update"]
    rocket = [f["fid"] for f in field if f["addr"] in (0x52FCC, 0x531AC)]
    debris = [f["fid"] for f in field if f["addr"] == 0x40638 and (f["w"], f["h"]) == (48, 16)]
    phases = [("cain", [(cain_legs, 2, 0, 40), (cain64, 4, -8, 6), (cain48, 3, 8, 22)]),
              ("w21", [(w21_torso, 32, 6, 0), (w21_legs, 2, 0, 26)]),
              ("truck", [(part, 8, 20, 10), (truck, 1, 0, 0)]),
              ("w51", [(w51, 16, 0, 0)]),
              ("misc", [(w35, 8, 0, 0), (rocket, 2, 60, 10), (debris, 1, 0, 40)]),
              ("mix", [(cain_legs, 2, 0, 0), (w21_legs, 2, 56, 4)])]
    for name, parts in phases:
        assert all(p[0] for p in parts), f"phase {name}: a part without frames"
    out.write_text("# generated by tools/bstest/l3poses.py\nset ::lf_len " + str(LF_LEN) + "\nset ::lf_phases {\n"
                   + "".join("    {" + name + " {" + " ".join("{{" + " ".join(map(str, fr)) + f"}} {per} {dx} {dy}}}"
                                                             for fr, per, dx, dy in parts) + "}}\n"
                             for name, parts in phases) + "}\n")
    print(f"{out}: {len(phases)} phases of {LF_LEN} ticks")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
