def hard_refs(procs) -> list[dict]:
    out = []
    for proc, site, d4, frames, level, evidence in HARD_REFS:
        name = procs.get(proc, (f"FUN_{proc:08x}", []))[0]
        out.append({"proc": proc, "proc_name": name, "site": site, "base": frames[0], "adjust": [],
                    "table": None, "ltable": None, "bltsize": d4, "frames": list(frames),
                    "level": level, "evidence": evidence})
    return out


def table_frames(main: bytes, base: int, offsets, d4) -> list[tuple[int, int]]:
    """(frame, BLTSIZE) of L2_HARD's and D4_TABLES' forms, in the table's order, repeats dropped."""
    def word(a: int, signed: bool) -> int:
        return struct.unpack_from(">h" if signed else ">H", main, a - 0x8000)[0]
    if isinstance(offsets[0], str):
        kind, t, n = offsets
        offs = [word(t + 2 * i, kind == "s") for i in range(n)]
    else:
        offs = list(offsets)
    sizes = [word(d4[1] + 2 * i, False) for i in range(len(offs))] if isinstance(d4, tuple) else [d4] * len(offs)
    return list(dict.fromkeys((base + o, s) for o, s in zip(offs, sizes)))


def frames_for(ref, main: bytes, ram_size: int, dedupe: bool = False) -> list[int]:
    """The frames of a reference. dedupe (level 2's catalogue): a table walk goes on past a repeated
    offset (the level-1 catalogue stops there)."""
    wb, h = ((ref["bltsize"] & 63) - 1) * 2, ref["bltsize"] >> 6
    fs = 5 * wb * h
    if ref.get("ltable") is not None:
        # a table of pointers (the index a type byte in steps of 4): from its first pointer into
        # the RAM image up to the first that is not (the pickups' $F964: entry 0 is code, the
        # entry after type 36 garbage)
        out = []
        t = ref["ltable"]
        for i in range(32):
            if not 0x8000 <= t + 4 * i < 0x8000 + len(main) - 3:
                break
            v = struct.unpack_from(">L", main, t + 4 * i - 0x8000)[0]
            if v % 2 == 0 and 0x10000 <= v <= ram_size - fs:
                out.append(v)
            elif out:
                break
        return list(dict.fromkeys(out))           # (in the table's order: its first one is the base)
    addrs = {ref["base"]}
    for a in ref["adjust"]:
        addrs |= {x + a for x in addrs}
    if ref["table"] is not None:
        offs = []
        t = ref["table"]
        for i in range(32):
            if not 0x8000 <= t + 2 * i < 0x8000 + len(main) - 1:
                break
            v = struct.unpack_from(">h", main, t + 2 * i - 0x8000)[0]
            if dedupe and v in offs:
                continue
            if v < 0 or v % fs or v > 40 * fs or (offs and v in offs):
                break
            offs.append(v)
        addrs = {x + o for x in addrs for o in offs} or addrs
    return sorted(addrs)


def mask_score(ram: bytes, addr: int, wb: int, h: int) -> float:
    """0..1: fraction of mask pixels without a transition to the neighbour; plus a sane density."""
    if addr < 0 or addr + 5 * wb * h > len(ram):
        return 0.0
    m = ram[addr:addr + wb * h]
    ones = sum(bin(b).count("1") for b in m)
    dens = ones / (wb * h * 8)
    if not 0.04 <= dens <= 0.97:
        return 0.0
    trans = 0
    for y in range(h):
        bits = int.from_bytes(m[y * wb:(y + 1) * wb], "big")
        trans += bin((bits ^ (bits >> 1)) & ((1 << (wb * 8 - 1)) - 1)).count("1")
    return 1 - trans / (h * (wb * 8 - 1))


def cmd_catalog() -> int:
    procs = load_procs()
    targets = draw_targets(procs)
    main = (ROOT / "build/extracted/boot/main_8000.bin").read_bytes()
    rams = {k: (ROOT / v[0]).read_bytes() for k, v in LEVELS.items()}
    refs = scan(procs, targets) + hard_refs(procs)
    plv = proc_levels(main)
    for r in refs:
        wb, h = ((r["bltsize"] & 63) - 1) * 2, r["bltsize"] >> 6
        r["width"], r["height"] = wb * 8, h
        if r.get("evidence", "").startswith("hard-coded"):
            r["score"] = {lv: round(sum(mask_score(ram, f, wb, h) for f in r["frames"]) / len(r["frames"]), 3)
                          for lv, ram in rams.items()}
            continue
        r["frames"] = frames_for(r, main, min(len(ram) for ram in rams.values()))
        if not r["frames"]:
            r["level"], r["evidence"] = None, "no frames"
            continue
        if r["base"] is None:
            r["base"] = r["frames"][0]
        score = {lv: round(sum(mask_score(ram, f, wb, h) for f in r["frames"]) / len(r["frames"]), 3)
                 for lv, ram in rams.items()}
        r["score"] = score
        levels = plv.get(r["proc"], set())
        base = r["base"]
        if PERMA[0] <= base < PERMA[1]:
            r["level"], r["evidence"] = "common", "PERMA (resident)"
        elif SPERMA[0] <= base < SPERMA[1] and levels and levels <= {"level1", "level2"}:
            r["level"], r["evidence"] = "common", "SPERMA (levels 1-2)"
        elif len(levels) == 1:
            r["level"], r["evidence"] = next(iter(levels)), "code (spawn list/special object)"
        elif levels:
            r["level"], r["evidence"] = "+".join(sorted(levels)), "code (several levels; per-level data)"
        else:
            best = max(score, key=score.get)
            r["level"] = best if score[best] >= 0.80 else None
            r["evidence"] = "inferred (mask score)"
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "catalog.json").write_text(json.dumps({"draw_targets": sorted(targets), "refs": refs}, indent=1))
    print(f"{len(procs)} routines read, draw wrappers: {[hex(t) for t in sorted(targets)]}")
    agg = defaultdict(int)
    for r in refs:
        agg[(r["level"], r["evidence"].split(" ")[0])] += 1
    print(f"{len(UNRESOLVED)} draw calls not followed (frames from the bench's coverage only): "
          + ", ".join(f"{hex(site)} ({name})" for _p, name, site in UNRESOLVED))
    print(f"{len(refs)} sprite references:")
    for (lv, ev), n in sorted(agg.items(), key=str):
        print(f"   {str(lv):24} {ev:10} {n}")
    return 0


def handlers(main: bytes, types) -> set[int]:
    """The handlers of the object types (OBJ_DESC: the descriptor's first word, relative)."""
    out = set()
    for t in types:
        d = OBJ_DESC + 16 * t
        out.add(d + struct.unpack_from(">h", main, d - 0x8000)[0])
    return out


def frame_bytes(ram: bytes, addr: int, w: int, h: int) -> bytes:
    return ram[addr:addr + 5 * (w // 8) * h]


def cmd_level2(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(prog="bobcatalog.py level2")
    ap.add_argument("--shared", type=Path, action="append", default=[],
                    help="level 1's bench coverage (default build/emu/cov_level1.json): its frames that level 2's "
                         "image holds too")
    ap.add_argument("--drawn", type=Path, action="append", default=[],
                    help="level 2's bench coverage (tools/amigacov.py --level 2): every frame must be listed")
    ap.add_argument("-o", "--out", type=Path, default=OUT / "catalog_l2.json")
    a = ap.parse_args(argv)
    procs = load_procs()
    targets = draw_targets(procs)
    main = (ROOT / "build/extracted/boot/main_8000.bin").read_bytes()
    ram1 = (ROOT / LEVELS["level1"][0]).read_bytes()
    ram2 = (ROOT / LEVELS["level2"][0]).read_bytes()
    mine = handlers(main, L2_TYPES) | L2_SPECIALS
    objects = handlers(main, range(1, 53)) | set(SPECIAL_LEVELS)
    shared = lambda f, w, h: frame_bytes(ram1, f, w, h) == frame_bytes(ram2, f, w, h)  # noqa: E731
    refs, seen = [], set()

    def add(proc: int, name: str, site: int, frames: list[tuple[int, int]], evidence: str) -> None:
        sizes: dict[int, list[int]] = {}
        for f, d4 in frames:
            sizes.setdefault(d4, []).append(f)
        for d4, fs in sizes.items():
            w, h = ((d4 & 63) - 1) * 16, d4 >> 6
            fs = [f for f in dict.fromkeys(fs) if 0x10000 <= f <= len(ram2) - 5 * (w // 8) * h
                  and (f, w, h) not in L2_NEVER]
            if not fs:
                continue
            seen.update((f, w, h) for f in fs)
            refs.append({"proc": proc, "proc_name": name, "site": site, "base": fs[0], "adjust": [], "table": None,
                         "ltable": None, "bltsize": d4, "width": w, "height": h, "frames": fs, "level": "level2",
                         "evidence": evidence})

    UNRESOLVED.clear()
    for r in scan(procs, targets, l2=True):
        if r["proc"] not in mine and r["proc"] in objects:
            continue                                    # (an object level 2 never spawns)
        if r.get("d4_table"):
            assert not r["adjust"], "a BLTSIZE table with A2 adjusts"
            frames = table_frames(main, r["base"], ("s", r["table"], D4_TABLES[r["d4_table"]]), ("t", r["d4_table"]))
            ev = f"scan, BLTSIZE from ${r['d4_table']:X} ({D4_TABLES[r['d4_table']]} entries, REA)"
        else:
            frames = [(f, r["bltsize"]) for f in frames_for(r, main, len(ram2), dedupe=True)]
            ev = "scan"
        if r["proc"] not in mine and not all(shared(f, ((d4 & 63) - 1) * 16, d4 >> 6) for f, d4 in frames):
            continue                                    # (shared code drawing another level's data)
        add(r["proc"], r["proc_name"], r["site"], frames, ev + ("" if r["proc"] in mine else "; shared code"))
    for proc, site, d4, frames, level, evidence in HARD_REFS:
        if "level2" in level.split("+"):
            add(proc, procs.get(proc, (f"FUN_{proc:08x}", []))[0], site, [(f, d4) for f in frames], evidence)
    for name, site, base, offsets, d4, evidence in L2_HARD:
        proc = next((p for p, (n, _) in procs.items() if n == name), 0)
        add(proc, name, site, table_frames(main, base, offsets, d4), evidence)
    gfx, blt, anim = BULLETS
    for t in range(1, 7):                               # (level 2's bullet types: 1-6)
        g, d4 = struct.unpack_from(">L", main, gfx + 4 * t - 0x8000)[0], struct.unpack_from(">H", main, blt + 4 * t - 0x8000)[0]
        step, lim = struct.unpack_from(">hh", main, anim + 4 * t - 0x8000)
        n = 1 if step <= 0 else lim // step + 1
        add(0xF3CE, "FUN_0000f3ce", 0xF488, [(g + k * max(step, 0), d4) for k in range(n)],
            f"REA $F3CE: bullet type {t} ($F4A4/$F500/$F55C + {4 * t})")
    for path in a.shared or [ROOT / "build/emu/cov_level1.json"]:
        frames = [(b["addr"], b["bltsize"]) for b in json.loads(path.read_text())["bobs"]
                  if (b["addr"], b["w"], b["h"]) not in seen and shared(b["addr"], b["w"], b["h"])]
        add(0, "drawn", 0, frames, f"level 1's bench coverage ({path.name}): shared code, the same bytes in level 2")
    missing = []
    for path in a.drawn:
        bobs = json.loads(path.read_text())["bobs"]
        missing += [(b["addr"], b["bltsize"]) for b in bobs if (b["addr"], b["w"], b["h"]) not in seen]
        add(0, "drawn", 0, missing, f"level 2's bench coverage ({path.name})")
    a.out.parent.mkdir(parents=True, exist_ok=True)
    a.out.write_text(json.dumps({"draw_targets": sorted(targets), "refs": refs}, indent=1))
    own = {k for k in seen if DATAL2[0] <= k[0] < DATAL2[1]}
    print(f"{a.out}: {len(refs)} references, {len(seen)} distinct frames ({len(own)} in DATAL2, "
          f"{len(seen) - len(own)} shared)")
    print(f"  {len(UNRESOLVED)} draw calls the scan does not follow (L2_HARD and the coverage give level 2's): "
          + ", ".join(f"{hex(site)} ({name})" for _p, name, site in UNRESOLVED))
    if missing:
        print(f"error: {len(missing)} frames of level 2's coverage the catalogue lacked: "
              + ", ".join(f"{f:X}:{d4:04X}" for f, d4 in missing), file=sys.stderr)
        return 1
    return 0


def drawn_list(path: Path) -> list[tuple[int, int]]:
    """(frame, BLTSIZE) of a bench coverage: tools/amigacov.py's "bobs", or a list of [addr, BLTSIZE, count]."""
    j = json.loads(path.read_text())
    if isinstance(j, dict):
        return [(b["addr"], b["bltsize"]) for b in j["bobs"]]
    return [(int(e[0]), int(e[1])) for e in j]


def cmd_level3(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(prog="bobcatalog.py level3")
    ap.add_argument("--shared", type=Path, action="append", default=[],
                    help="level 1's bench coverage (default build/emu/cov_level1.json): its PERMA frames with the "
                         "same bytes in level 3's image")
    ap.add_argument("--drawn", type=Path, action="append", default=[],
                    help="level 3's bench coverage (tools/amigacov.py --level 3, or [addr, BLTSIZE, count] lists): "
                         "every frame must be listed")
    ap.add_argument("-o", "--out", type=Path, default=OUT / "catalog_l3.json")
    a = ap.parse_args(argv)
    procs = load_procs()
    main = (ROOT / "build/extracted/boot/main_8000.bin").read_bytes()
    ram1 = (ROOT / LEVELS["level1"][0]).read_bytes()
    ram3 = (ROOT / LEVELS["level3"][0]).read_bytes()
    refs, seen, src = [], set(), {}

    def add(proc: int, name: str, site: int, frames: list[tuple[int, int]], evidence: str) -> None:
        sizes: dict[int, list[int]] = {}
        for f, d4 in frames:
            sizes.setdefault(d4, []).append(f)
        for d4, fs in sizes.items():
            w, h = ((d4 & 63) - 1) * 16, d4 >> 6
            fs = [f for f in dict.fromkeys(fs) if 0x10000 <= f <= len(ram3) - 5 * (w // 8) * h and (f, w, h) not in seen]
            if not fs:
                continue
            seen.update((f, w, h) for f in fs)
            src.update({(f, w, h): name for f in fs})
            refs.append({"proc": proc, "proc_name": name, "site": site, "base": fs[0], "adjust": [], "table": None,
                         "ltable": None, "bltsize": d4, "width": w, "height": h, "frames": fs, "level": "level3",
                         "evidence": evidence})

    for name, site, base, offsets, d4, evidence in L3_HARD:
        proc = next((p for p, (n, _) in procs.items() if n == name), 0)
        add(proc, name, site, table_frames(main, base, offsets, d4), evidence)
    gfx, blt, anim = BULLETS
    for t in L3_BULLETS:
        g, d4 = struct.unpack_from(">L", main, gfx + 4 * t - 0x8000)[0], struct.unpack_from(">H", main, blt + 4 * t - 0x8000)[0]
        step, lim = struct.unpack_from(">hh", main, anim + 4 * t - 0x8000)
        n = 1 if step <= 0 else lim // step + 2             # ($F426: the offset grows by the step while it
        add(0xF3CE, "FUN_0000f3ce", 0xF488, [(g + k * max(step, 0), d4) for k in range(n)],   # is at most the
            f"REA $F3CE: bullet type {t:X}h ($F4A4/$F500/$F55C + {4 * t})")                    # limit, then 0)
    first, last, bl, gf = EXPL_STEPS
    for t in L3_EXPL:
        k0, k1 = main[first + t - 0x8000], main[last + t - 0x8000]
        add(0xF080, "FUN_0000f080", 0xF12A,
            [(struct.unpack_from(">L", main, gf + 4 * k - 0x8000)[0], struct.unpack_from(">H", main, bl + 2 * k - 0x8000)[0])
             for k in range(k0, k1 + 1)],
            f"REA $F080: explosion type {t}, steps {k0}-{k1} ($F3BC/$F3C5; $F140 BLTSIZE, $F1C6 gfx)")
    add(0xF900, "FUN_0000f900", 0xF95C,
        [(struct.unpack_from(">L", main, PICKUPS + t - 0x8000)[0], 0x402) for t in L3_PICKUPS],
        "REA $F900: the pickups level 3 drops ($F964 + type)")
    shared = lambda f, w, h: frame_bytes(ram1, f, w, h) == frame_bytes(ram3, f, w, h)  # noqa: E731
    for path in a.shared or [ROOT / "build/emu/cov_level1.json"]:
        frames = [(f, d4) for f, d4 in drawn_list(path) if PERMA[0] <= f < PERMA[1]
                  and shared(f, ((d4 & 63) - 1) * 16, d4 >> 6)]
        add(0, "drawn", 0, frames, f"level 1's bench coverage ({path.name}): PERMA, the same bytes in level 3")
    unexplained = []
    for path in a.drawn:
        frames = [(f, d4) for f, d4 in drawn_list(path) if (f, ((d4 & 63) - 1) * 16, d4 >> 6) not in seen]
        unexplained += frames
        add(0, "drawn", 0, frames, f"level 3's bench coverage ({path.name})")
    a.out.parent.mkdir(parents=True, exist_ok=True)
    a.out.write_text(json.dumps({"refs": refs}, indent=1))
    own = {k for k in seen if DATAL3[0] <= k[0] < DATAL3[1]}
    print(f"{a.out}: {len(refs)} references, {len(seen)} distinct frames ({len(own)} in DATAL3, "
          f"{len(seen) - len(own)} shared)")
    if unexplained:
        print(f"  {len(unexplained)} frames of the coverage the tables do not explain (taken as drawn): "
              + ", ".join(f"{f:X}:{d4:04X}" for f, d4 in unexplained))
    return 0


def cmd_sheets(catalog: Path | None = None) -> int:
    cat = json.loads((catalog or OUT / "catalog.json").read_text())
    main = (ROOT / "build/extracted/boot/main_8000.bin").read_bytes()
    groups = defaultdict(list)
    for r in cat["refs"]:
        if r["level"]:
            for lv in r["level"].split("+"):
                groups[(lv, r["proc_name"])].append(r)
    for (lv, pname), refs in sorted(groups.items()):
        src = LEVELS["level1" if lv == "common" else lv]
        ram = (ROOT / src[0]).read_bytes()
        po = src[1] - 0x8000
        pal = [(0, 0, 0)] + [rgb12_to_rgb24(struct.unpack_from(">H", main, po + 2 * i)[0]) for i in range(15)]
        tiles = []
        for r in refs:
            wb, h = r["width"] // 8, r["height"]
            for f in r["frames"]:
                tiles.append((f, wb, h))
        tiles = list(dict.fromkeys(tiles))
        cell_w = max(wb for _f, wb, _h in tiles) * 8 + 2
        cell_h = max(h for _f, _wb, h in tiles) + 2
        cols = min(10, len(tiles))
        rows = (len(tiles) + cols - 1) // cols
        S = 3
        W, H = cols * cell_w, rows * cell_h
        canvas = [[(60, 60, 60)] * W for _ in range(H)]
        for i, (f, wb, h) in enumerate(tiles):
            ox, oy = (i % cols) * cell_w + 1, (i // cols) * cell_h + 1
            ps = wb * h
            for y in range(h):
                for x in range(wb * 8):
                    byte, bit = y * wb + (x >> 3), 0x80 >> (x & 7)
                    if not ram[f + byte] & bit:
                        canvas[oy + y][ox + x] = (255, 0, 255)
                        continue
                    v = sum(1 << p for p in range(4) if ram[f + ps * (p + 1) + byte] & bit)
                    canvas[oy + y][ox + x] = pal[v]
        rows_px = [b"".join(bytes(c) * S for c in row) for row in canvas for _ in range(S)]
        path = OUT / f"{lv}_{re.sub(r'[^A-Za-z0-9_]+', '_', pname)}.png"
        write_png(path, W * S, H * S, rows_px)
        print(f"{path.name}: {len(tiles)} frames")
    return 0


if __name__ == "__main__":
    cmd = sys.argv[1] if len(sys.argv) > 1 else "catalog"
    if cmd == "level2":
        raise SystemExit(cmd_level2(sys.argv[2:]))
    if cmd == "level3":
        raise SystemExit(cmd_level3(sys.argv[2:]))
    raise SystemExit(cmd_catalog() if cmd == "catalog" else
                     cmd_sheets(Path(sys.argv[2]) if len(sys.argv) > 2 else None))
