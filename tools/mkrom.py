KEY_BITS = {"u": 0x01, "d": 0x02, "l": 0x04, "r": 0x08, "f": 0x10}   # the joystick byte ($802E)


def rom_banks(used: int, at_least: int = 0) -> int:
    """The image's banks: the next power of two (a device masks bank numbers to its size)."""
    n = 1
    while n < used or n < at_least:
        n *= 2
    return n


def guard_tag(banks: int) -> bytes:
    """msx/cold.asm rom_guard's tag (rg_tag), at the last bank's GUARD_AT."""
    return b"RC2BANK" + bytes([banks - 1])


def input_inc(script: str, tele: str = "") -> str:
    """input.inc (bank BANK_INPUT at A000h, msx/player.asm script_bits / script_tick): the JOY
    script as runs [frames (dw), joystick bits (db)] of the bits per game frame (every entry
    that covers a frame ORed), 0 after the last; the TELE teleports as [game frame, x, y]."""
    items = []
    for item in filter(None, script.split(",")):
        start, count, keys = item.split(":")
        bits = 0
        for k in keys:
            bits |= KEY_BITS[k]
        items.append((int(start), int(count), bits))
    end = max((f + c for f, c, _ in items), default=0)
    frames = [0] * end
    for f, c, bits in items:
        for n in range(f, f + c):
            frames[n] |= bits
    runs = []
    for b in frames:
        if runs and runs[-1][1] == b and runs[-1][0] < 0xFFFF:
            runs[-1][0] += 1
        else:
            runs.append([1, b])
    lines = ["; generated by tools/mkrom.py: joystick script (JOY=..., TELE=...; INPUT_SCRIPT in options.inc)",
             "input_script:"]
    lines += [f"        dw {n}\n        db 0x{b:02X}" for n, b in runs]
    lines.append("        dw 0")
    lines.append("input_tele:")
    for item in filter(None, tele.split(",")):
        f, x, y = (int(v, 0) for v in item.split(":"))
        lines.append(f"        dw {f}, {x}, {y}")
    lines.append("        dw 0xFFFF")
    return "\n".join(lines) + "\n"


