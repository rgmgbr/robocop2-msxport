KEY_BITS = {"u": 0x01, "d": 0x02, "l": 0x04, "r": 0x08, "f": 0x10}   # the joystick byte ($802E)


def rom_banks(used: int, at_least: int = 0) -> int:
    """The image's banks: the next power of two (a device masks bank numbers to its size)."""
    n = 1
    while n < used or n < at_least:
        n *= 2
    return n


def guard_tag(banks: int) -> bytes:
    """msx/cold.asm rom_guard's tag (rg_tag), at the last bank's GUARD_AT."""
    return b"RC2BANK" + bytes([banks - 1])


def input_inc(script: str, tele: str = "") -> str:
    """input.inc (bank BANK_INPUT at A000h, msx/player.asm script_bits / script_tick): the JOY
    script as runs [frames (dw), joystick bits (db)] of the bits per game frame (every entry
    that covers a frame ORed), 0 after the last; the TELE teleports as [game frame, x, y]."""
    items = []
    for item in filter(None, script.split(",")):
        start, count, keys = item.split(":")
        bits = 0
        for k in keys:
            bits |= KEY_BITS[k]
        items.append((int(start), int(count), bits))
    end = max((f + c for f, c, _ in items), default=0)
    frames = [0] * end
    for f, c, bits in items:
        for n in range(f, f + c):
            frames[n] |= bits
    runs = []
    for b in frames:
        if runs and runs[-1][1] == b and runs[-1][0] < 0xFFFF:
            runs[-1][0] += 1
        else:
            runs.append([1, b])
    lines = ["; generated by tools/mkrom.py: joystick script (JOY=..., TELE=...; INPUT_SCRIPT in options.inc)",
             "input_script:"]
    lines += [f"        dw {n}\n        db 0x{b:02X}" for n, b in runs]
    lines.append("        dw 0")
    lines.append("input_tele:")
    for item in filter(None, tele.split(",")):
        f, x, y = (int(v, 0) for v in item.split(":"))
        lines.append(f"        dw {f}, {x}, {y}")
    lines.append("        dw 0xFFFF")
    return "\n".join(lines) + "\n"


HASH_SLOTS = 512                    # BOBHASH: 512 slots of 8 bytes and the overflow ones after them
HASH_EXTRA = 16


def bob_hash(sprites_json: Path) -> bytes:
    """The level's BOB frames (tools/msxsprites.py) by the game's (A2, D4): slots of 8 bytes [A2 (3,
    low first), D4 (2), frame id, silhouette, 0] from slot h = the XOR of those 5 bytes, plus 256
    when bit 4 of A2 is set (msx/bob.asm bf_show), on into the next slots when taken (no wrap: the
    extra slots after the 512 take the overflow); an empty slot has id FFh. A play-field frame
    (id FIELD_ID0 + its index) whose hit flash shows as a sprite silhouette has that sprite frame
    in "silhouette" (FFh: none); the sprite frame itself is then not in the table."""
    data = json.loads(sprites_json.read_text())
    frames = [f for f in data.get("bobs", []) if not f.get("spark")]
    if len(data.get("bobs", [])) > FIELD_ID0:            # (the hit spark's ids too)
        raise SystemExit(f"{len(data['bobs'])} BOB frames: too many for the frame ids")
    frames = [f for f in frames if "field" not in f]
    frames += [dict(f, id=FIELD_ID0 + f["fid"]) for f in data.get("field", [])]   # (drawn into the play field)
    table = bytearray(b"\x00\x00\x00\x00\x00\xff\x00\x00" * (HASH_SLOTS + HASH_EXTRA))
    for f in frames:
        a2, d4 = f["addr"], (f["h"] << 6) | (f["w"] // 16 + 1)
        key = bytes([a2 & 0xFF, (a2 >> 8) & 0xFF, (a2 >> 16) & 0xFF, d4 & 0xFF, d4 >> 8])
        h = (key[0] ^ key[1] ^ key[2] ^ key[3] ^ key[4]) | ((key[0] >> 4) & 1) << 8
        while table[8 * h + 5] != 0xFF:
            h += 1
        if h >= HASH_SLOTS + HASH_EXTRA:
            raise SystemExit("BOBHASH: the overflow slots are full")
        table[8 * h:8 * h + 8] = key + bytes([f["id"], f.get("sil", 0xFF), 0])
    return bytes(table)


def offsets(blob: bytes, n: int) -> list[int]:
    """The n little-endian 24-bit offsets at the start of a music blob (tools/msxscc.py, msxfm.py)."""
    return [blob[3 * i] | blob[3 * i + 1] << 8 | blob[3 * i + 2] << 16 for i in range(n)]


def fx_entries(blob: bytes) -> list[tuple[int, int, int]]:
    """An sccfx.bin layout's effects (tools/msxsccfx.py): (channel, SCC stream's offset, PSG
    stream's, 0 = none), up to the first stream (the header's end)."""
    out, first = [], offsets(blob, 1)[0]
    while 4 + 7 * len(out) < first:
        e = 4 + 7 * len(out)
        so = blob[e + 1] | blob[e + 2] << 8 | blob[e + 3] << 16
        po = blob[e + 4] | blob[e + 5] << 8 | blob[e + 6] << 16
        out.append((blob[e], so, po))
        first = min([first] + [o for o in (so, po) if o])
    if 4 + 7 * len(out) != first:
        raise SystemExit("error: an sccfx blob's header does not end at its first stream")
    return out


def fx_append(base: bytes, more: bytes) -> bytes:
    """sccfx.bin with the effects of another blob in its layout (tools/msxgun.py gun_scc.bin)
    after its own: one header for all (every stream's offset moved past the entries added), the
    streams of both, the waveform tables joined (the added SCC streams' waveform numbers moved
    past the base's)."""
    b_fx, m_fx = fx_entries(base), fx_entries(more)
    (b_tab,), (m_tab,) = offsets(base, 1), offsets(more, 1)
    head = 4 + 7 * (len(b_fx) + len(m_fx))
    b_streams = base[4 + 7 * len(b_fx):b_tab]
    m_streams = bytearray(more[4 + 7 * len(m_fx):m_tab])
    m0 = 4 + 7 * len(m_fx)
    for _, so, _ in m_fx:                   # (the waveform bytes: ctl bit 5, after the period word)
        p = so - m0 if so else None
        while p is not None and m_streams[p]:
            ctl = m_streams[p + 1]
            p += 2 + (2 if ctl & 0x10 else 0)
            if ctl & 0x20:
                m_streams[p] += base[3]
                p += 1
    def u24(v: int) -> bytes:
        return bytes([v & 0xFF, v >> 8 & 0xFF, v >> 16])
    def entry(ch: int, so: int, po: int, shift: int) -> bytes:
        return bytes([ch]) + u24(so + shift if so else 0) + u24(po + shift if po else 0)
    tab = head + len(b_streams) + len(m_streams)
    w = base[3] + more[3]
    if w > 255:
        raise SystemExit("error: more than 255 effect waveforms")
    return (u24(tab) + bytes([w])
            + b"".join(entry(*e, head - (4 + 7 * len(b_fx))) for e in b_fx)
            + b"".join(entry(*e, head + len(b_streams) - m0) for e in m_fx)
            + b_streams + bytes(m_streams) + base[b_tab:b_tab + 32 * base[3]] + more[m_tab:m_tab + 32 * more[3]])


MVK_SCC, MVK_PSG, MVK_FM, MVK_RHY = range(4)     # msx/music.asm's stream kinds


def voice_at(blob: bytes, start: int, bank: int, kind: int, tick: int, since: int) -> bytes:
    """A music.asm voice record (MV_..., 16 bytes) as mus_adv leaves it after `tick` of the stream
    at `start` of a blob from `bank` on (records of dur, ctl and the fields its bits give): the
    next record's address and bank, the ticks left, the ctl, period, aux and rhythm volumes in
    effect, the stream's start, MV_NEW for vm_music's outputs (every field; bit 7 when an OPLL
    note began after `since`) and the kind; the rhythm's keys cleared (struck when its record
    began)."""
    word, byte = (0x40, 0x80) if kind == MVK_PSG else (0x10, 0x20)
    p, t, per, aux, rv, again = start, 0, 0, 0, [0, 0, 0], False
    while True:
        d = blob[p]
        if d == 0:
            p = start
            continue
        ctl, q = blob[p + 1], p + 2
        if kind == MVK_RHY:
            if ctl & 0x20:
                rv, q = list(blob[q:q + 3]), q + 3
        else:
            if ctl & word:
                per, q = blob[q] | blob[q + 1] << 8, q + 2
            if ctl & byte:
                aux, q = blob[q], q + 1
        again |= kind == MVK_FM and bool(ctl & 0x80) and since < t <= tick
        if t + d > tick:
            break
        t, p = t + d, q
    if kind == MVK_RHY:
        ctl &= 0xE0

    def where(off: int) -> list[int]:
        a = 0x8000 + off % BANK
        return [a & 0xFF, a >> 8, bank + off // BANK]
    return bytes(where(q) + [d - (tick - t), ctl, per & 0xFF, per >> 8, aux] + where(start)
                 + [0x31 | (0x80 if again else 0)] + rv + [kind])


def stream_ticks(blob: bytes, start: int, kind: int) -> int:
    """The ticks of the stream at `start` of a music blob up to its end (a duration of 0)."""
    word, byte = (0x40, 0x80) if kind == MVK_PSG else (0x10, 0x20)
    p, t = start, 0
    while blob[p]:
        t, ctl, p = t + blob[p], blob[p + 1], p + 2
        if kind == MVK_RHY:
            p += 3 if ctl & 0x20 else 0
        else:
            p += (2 if ctl & word else 0) + (1 if ctl & byte else 0)
    return t


def voice_inc(label: str, blob: bytes, bank: int, streams: list[tuple[int, int]], tick: int, since: int) -> list[str]:
    """voice_at of a blob's streams (header index, kind) as z80asm lines after a label."""
    out = [f"{label}:"]
    for i, kind in streams:
        rec = voice_at(blob, offsets(blob, 4)[i], bank, kind, tick, since)
        out.append("        db " + ", ".join(str(v) for v in rec))
    return out


def music_inc(scc: bytes, scc_bank: int, waves_n: int, fm: bytes, fm_bank: int, tick: int, since: int,
              sccfx: bytes) -> str:
    """music.inc (BANK_MUSIC, msx/music.asm): each stream's bank and address in the 8000h window
    (the blobs start at their banks), the SCC's waveforms, the OPLL's patch block, and the
    voices' records at `tick`, the first after the speech (vm_music: mus_snap_...)."""
    def entries(label: str, blob: bytes, bank: int, what: str) -> list[str]:
        out = [f"{label}:{' ' * max(1, 28 - len(label))}; {what}: bank, address (8000h window)"]
        for off in offsets(blob, 4):
            out.append(f"        db {bank + off // BANK}\n        dw 0x{0x8000 + off % BANK:04X}")
        return out
    def db(data: bytes) -> list[str]:
        return ["        db " + ", ".join(str(b) for b in data[i:i + 16]) for i in range(0, len(data), 16)]
    so, fo = offsets(scc, 5), offsets(fm, 5)
    waves = scc[so[4]:so[4] + 32 * waves_n]
    lengths = {stream_ticks(blob, offsets(blob, 4)[i], kind)
               for blob, kinds in ((scc, (MVK_SCC,) * 3 + (MVK_PSG,)), (fm, (MVK_FM,) * 3 + (MVK_RHY,)))
               for i, kind in enumerate(kinds)}
    if len(lengths) != 1:
        raise SystemExit(f"the title music's streams last {sorted(lengths)} ticks: music.asm mus_adv needs one length")
    lines = ["; generated by tools/mkrom.py: the title music's streams (tools/msxscc.py, tools/msxfm.py)",
             f"MUS_TICKS:  equ {lengths.pop()}              ; every stream's length (the tune's: music.asm mus_adv)"]
    lines += entries("mus_scc", scc, scc_bank, "the SCC's three voices, then the drums on PSG voice C")
    lines += entries("mus_fm", fm, fm_bank, "the OPLL's three voices, then its rhythm")
    lines.append("fm_patch:                           ; the custom instrument (00h-07h), the rhythm's pitches"
                 " (16h-18h, 26h-28h)")
    lines += db(fm[fo[4]:fo[4] + 14])
    lines.append(f"scc_waves:                          ; {len(waves) // 32} waveforms of 32 bytes")
    lines += db(waves)
    fwo, fwn = offsets(sccfx, 1)[0], sccfx[3]
    lines.append(f"fx_waves:                           ; the sound effects' {fwn} waveforms (tools/msxsccfx.py)")
    lines += db(sccfx[fwo:fwo + 32 * fwn])
    lines.append(f"; the voices as mus_adv leaves them after tick {tick} (the first after the speech: vm_music)")
    lines += voice_inc("mus_snap_scc", scc, scc_bank, [(0, MVK_SCC), (1, MVK_SCC), (2, MVK_SCC)], tick, since)
    lines += voice_inc("mus_snap_psg", scc, scc_bank, [(3, MVK_PSG)], tick, since)
    lines += voice_inc("mus_snap_fm", fm, fm_bank, [(0, MVK_FM), (1, MVK_FM), (2, MVK_FM)], tick, since)
    lines += voice_inc("mus_snap_rhy", fm, fm_bank, [(3, MVK_RHY)], tick, since)
    lines.append("scc_time_end:                       ; (the end of the tables music.asm may read with 3Fh at 9000h,"
                 " the code that does is before them: with 3Fh the MSX Pico+ also shows the SCC at B800h-BFFFh;"
                 " tools/mkrom.py main checks it)")
    return "\n".join(lines) + "\n"


# Brainstorm's music and effects (tools/msxtune.py pzm.bin, msx/tune.asm)
PZM_HEADER = 47
PZM_KINDS = (MVK_SCC,) * 3 + (MVK_PSG,) + (MVK_FM,) * 3 + (MVK_RHY,) + (MVK_PSG,) * 3   # its streams


def pzm_parse(blob: bytes) -> dict:
    """pzm.bin's header (tools/msxtune.py): the eleven streams (the SCC version's voices 0-2 and PSG
    drums, the OPLL's channels 0-2 and rhythm, the PSG version's voices A-C), the SCC waveform table
    and its count W, the OPLL's patch block, the effects' table (per effect: its length, its SCC
    stream and ticks, its PSG stream and ticks), the tune's ticks, the first effect and how many."""
    def r24(i: int) -> int:
        return blob[i] | blob[i + 1] << 8 | blob[i + 2] << 16
    out = {"streams": [r24(3 * k) for k in range(11)], "waves": r24(33), "patch": r24(36), "fx": r24(39),
           "W": blob[42], "T": blob[43] | blob[44] << 8, "fx0": blob[45], "fxn": blob[46], "effects": []}
    for k in range(out["fxn"]):
        e = out["fx"] + 9 * k
        out["effects"].append({"len": blob[e], "scc": r24(e + 1), "scc_ticks": blob[e + 4],
                               "psg": r24(e + 5), "psg_ticks": blob[e + 8]})
    return out


def scc_wave_numbers(blob: bytes, start: int) -> list[int]:
    """The waveform numbers an SCC stream's records give (ctl bit 5: the byte after the period word)."""
    out, p = [], start
    while blob[p]:
        ctl = blob[p + 1]
        p += 2 + (2 if ctl & 0x10 else 0)
        if ctl & 0x20:
            out.append(blob[p])
            p += 1
    return out


def pzm_check(blob: bytes) -> None:
    """pzm.bin as msx/tune.asm reads it: every tune stream lasts the tune, every effect's streams
    their ticks, within its length, and its length below 255 (tune.asm tn_go keeps the effect voice
    busy for its length + 1 ticks, a byte); the SCC waveforms in the table, 32-byte aligned in the
    blob (so none crosses a bank: tune.asm tn_wv reads one in the 8000h window)."""
    hd = pzm_parse(blob)
    if hd["streams"][0] != PZM_HEADER or not hd["fxn"] or hd["waves"] % 32:
        raise SystemExit("error: pzm.bin's header")
    ticks = [stream_ticks(blob, o, k) for o, k in zip(hd["streams"], PZM_KINDS)]
    if set(ticks) != {hd["T"]}:
        raise SystemExit(f"error: pzm.bin's streams last {ticks} ticks, the tune {hd['T']}")
    for e in hd["effects"]:
        longest = max(e["scc_ticks"], e["psg_ticks"])
        if (stream_ticks(blob, e["scc"], MVK_SCC), stream_ticks(blob, e["psg"], MVK_PSG)) != \
                (e["scc_ticks"], e["psg_ticks"]) or longest > e["len"] or longest + 1 > 255:
            raise SystemExit("error: pzm.bin: an effect's streams do not last their ticks")
        if e["len"] + 1 > 255:
            raise SystemExit("error: pzm.bin: an effect longer than 254 ticks (tune.asm tn_go: busy for its "
                             "length + 1, a byte)")
    used = [w for o in hd["streams"][:3] + [e["scc"] for e in hd["effects"]] for w in scc_wave_numbers(blob, o)]
    if max(used) >= hd["W"]:
        raise SystemExit("error: pzm.bin: an SCC waveform past its table")


def tune_inc(blob: bytes, bank: int) -> str:
    """tune.inc (BANK_MUSIC, after voice.inc: msx/tune.asm): Brainstorm's descriptor pz_desc
    (tune.asm TD_...: per chip set the streams' bank and address in the 8000h window, the length,
    the OPLL's patch block, the effects' table, the SCC waveforms' bank and address) and pz_fx (per
    effect, TF_...: its length, its SCC stream and ticks + 1, its PSG stream and ticks + 1); the
    streams and the waveforms stay in pzm.bin's banks, from `bank` on."""
    hd = pzm_parse(blob)
    def where(off: int) -> str:
        return f"db {bank + off // BANK}\n        dw 0x{0x8000 + off % BANK:04X}"
    def db(data: bytes) -> list[str]:
        return ["        db " + ", ".join(str(b) for b in data[i:i + 16]) for i in range(0, len(data), 16)]
    names = ("the SCC's voice 0", "voice 1", "voice 2", "the drums on PSG voice C", "the OPLL's channel 0",
             "channel 1", "channel 2", "its rhythm", "the PSG alone: voice A", "voice B", "voice C")
    lines = [f"; generated by tools/mkrom.py: Brainstorm's music and effects (tools/msxtune.py pzm.bin, from bank "
             f"{bank} on), msx/tune.asm",
             f"PZ_TICKS:   equ {hd['T']}              ; PZM tune 1's length (then silent)",
             "pz_desc:                            ; its descriptor (tune.asm TD_...)"]
    for o, n in zip(hd["streams"], names):
        lines.append(f"        {where(o)}{' ' * 8}; {n}")
    lines.append("        dw PZ_TICKS")
    lines.append("                                    ; the OPLL's custom instrument, the rhythm's pitches")
    lines += db(blob[hd["patch"]:hd["patch"] + 14])
    lines.append(f"        dw pz_fx\n        db {hd['fx0']}, {hd['fxn']}")
    lines.append(f"        {where(hd['waves'])}{' ' * 8}; its {hd['W']} SCC waveforms (32 bytes each)")
    lines.append("pz_fx:                              ; its effects (tune.asm TF_...): length, SCC stream and"
                 " ticks + 1, PSG stream and ticks + 1")
    for k, e in enumerate(hd["effects"]):
        lines.append(f"        db {e['len']}{' ' * 8}; effect {hd['fx0'] + k}")
        lines.append(f"        {where(e['scc'])}\n        db {e['scc_ticks'] + 1}")
        lines.append(f"        {where(e['psg'])}\n        db {e['psg_ticks'] + 1}")
    return "\n".join(lines) + "\n"


def equates(path: Path) -> dict[str, int]:
    out = {}
    for line in path.read_text().splitlines():
        if ": equ " in line:
            k, v = line.split(": equ ")
            out[k.strip()] = int(v.split()[0], 0)
    return out


